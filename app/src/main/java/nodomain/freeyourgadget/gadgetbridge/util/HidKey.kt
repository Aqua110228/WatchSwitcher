    LEFT_META(0xe3, "Left Meta", true),
    RIGHT_CTRL(0xe4, "Right Ctrl", true),
    RIGHT_SHIFT(0xe5, "Right Shift", true),
    RIGHT_ALT(0xe6, "Right Alt", true),
    RIGHT_META(0xe7, "Right Meta", true),

    A(0x04, "A"),
    B(0x05, "B"),
    C(0x06, "C"),
    D(0x07, "D"),
    E(0x08, "E"),
    F(0x09, "F"),
    G(0x0a, "G"),
    H(0x0b, "H"),
    I(0x0c, "I"),
    J(0x0d, "J"),
    K(0x0e, "K"),
    L(0x0f, "L"),
    M(0x10, "M"),
    N(0x11, "N"),
    O(0x12, "O"),
    P(0x13, "P"),
    Q(0x14, "Q"),

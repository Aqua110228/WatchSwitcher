    MEDIA_COFFEE(0xf9, "Media Lock"),
    MEDIA_REFRESH(0xfa, "Media Refresh"),
    MEDIA_CALC(0xfb, "Media Calculator"),
    ;

    val prefValue: String
        get() = name.lowercase()

    companion object {
        private val BY_USAGE = entries.associateBy { it.usage }
        private val BY_PREF_VALUE = entries.associateBy { it.prefValue }

        fun fromUsage(usage: Int): HidKey? = BY_USAGE[usage]

        fun fromPrefValue(value: String): HidKey? = BY_PREF_VALUE[value]
    }
}

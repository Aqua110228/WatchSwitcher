    F19(0x6e, "F19"),
    F20(0x6f, "F20"),
    F21(0x70, "F21"),
    F22(0x71, "F22"),
    F23(0x72, "F23"),
    F24(0x73, "F24"),

    PRINT_SCREEN(0x46, "Print Screen"),
    SCROLL_LOCK(0x47, "Scroll Lock"),
    PAUSE(0x48, "Pause"),
    INSERT(0x49, "Insert"),
    HOME(0x4a, "Home"),
    PAGE_UP(0x4b, "Page Up"),
